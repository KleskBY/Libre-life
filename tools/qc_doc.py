# Locked-name contracts
# ---------------------------------------------------------------------------


def load_locked() -> dict[str, list[str]]:
    """{identifier: [reason, ...]} from the generated denylist."""
    out: dict[str, list[str]] = {}
    p = SRC / "NAMING_LOCKED.txt"
    if not p.exists():
        return out
    for raw in p.read_text(encoding="utf-8").splitlines():
        if raw.startswith("#") or not raw.strip():
            continue
        parts = raw.split("\t")
        if len(parts) >= 2:
            out[parts[0].strip()] = [r.strip() for r in parts[1].split(",")]
    return out


def reasons_of(locked: dict[str, list[str]], name: str, kind: str) -> list[str]:
    return [r for r in locked.get(name, []) if r.startswith(kind)]


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------


def up_to_root(page_rel: str) -> str:
    """`../` prefix taking a generated page back to the repo root.

    Pages nest arbitrarily deep (`docs/reference/serverqc/ai/nodegraph.md`), so a
    fixed `../../` silently produced links into `docs/reference/src/...`.
    """
    depth = 2 + page_rel.count("/")  # docs/ + reference/ + each sub-directory
    return "../" * depth


def src_link(path: Path, line: int, prefix: str) -> str:
    rel = path.resolve().relative_to(REPO).as_posix()
    return f"[`{rel}:{line}`]({prefix}{rel}#L{line})"


def signature(d: qc_common.Definition) -> str:
    if d.kind == "function":
        params = " ".join(d.params.split())
        return f"{d.ret} {d.name}({params})"
    if d.kind == "field":
        return f".{d.ret} {d.name}"
    if d.kind == "define":
        return f"#define {d.name}"
    return f"{d.ret} {d.name}".strip()


def render_doc(doc: Doc, indent: str = "") -> list[str]:
    out: list[str] = []
    if doc.summary:
        out.append(indent + doc.summary)
    for line in doc.body:
        out.append(indent + line if line else "")
    for tag in ("param", "return", "see", "mapkey", "spawnflag", "frozen", "deprecated"):
        for value in doc.tags.get(tag, []):
            out.append(f"{indent}- **{tag}** — {value}")
    if "usehl" in doc.tags:
        out.append(f"{indent}- **usehl** — Half-Life four-argument Use handler.")
    return out


