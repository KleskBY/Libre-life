#!/usr/bin/env python3
"""Generate the Markdown code reference under `docs/reference/` from QuakeC source.

    python tools/qc_doc.py build       # write docs/reference/
    python tools/qc_doc.py check       # exit 1 if the tree would change (drift gate)
    python tools/qc_doc.py coverage    # undocumented public definitions, worst first

Why not Doxygen. Doxygen has no QuakeC language; `EXTENSION_MAPPING = qc=C` is the
only hook and its C parser cannot read this codebase:

  * ~1300 old-style definitions -- `void() worldspawn = {`,
    `void(entity e, float chan, ...) sound = #8;`
  * ~1000 `.field` declarations -- `.float q1_monster;` is the map-keyvalue ABI,
    the single most important thing to document, and it is not C syntax
  * per-target semantics -- one shared file compiles into two or three VMs
    against different engine ABIs, which Doxygen cannot express at all

`qc_common` already solves all three (it backs the naming tooling), so the
generator is a back end over it rather than a new parser.

Doc-comment convention (design rationale and porting notes belong in `docs/`,
not in the sources; short trailing notes on the line they annotate are fine):

    //! @file   Node navigation graph.
    //! @target SVQC

    /// Decide whether two nodes should be linked.
    /// @param a,b  node indices
    /// @return TRUE if linkable; sets g_node_door to a blocking door's targetname
    float NodeGraph_LinkValid(float a, float b)

    .float tank_yawRate;   //!< @mapkey yawrate  parsed from __fullspawndata

Plain `//` comments directly above a definition are picked up too, so existing
comments become documentation without having to be reformatted first.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qc_common  # noqa: E402

REPO = qc_common.REPO
SRC = qc_common.SRC
DOCS = REPO / "docs" / "reference"

BANNER = (
    "<!-- GENERATED by tools/qc_doc.py -- do not hand-edit.\n"
    "     Edit the doc comments in src/ and re-run `python tools/qc_doc.py build`. -->\n"
)

TARGET_LABEL = {"serverqc": "SVQC", "clientqc": "CSQC", "menuqc": "MENUQC"}
TARGET_DAT = {
    "serverqc": "data/progs.dat",
    "clientqc": "data/csprogs.dat",
    "menuqc": "data/menu.dat",
}

COMMENT_LINE = re.compile(r"^\s*(?://|/\*|\*(?!/)|\*/)")
DOC_MARK = re.compile(r"^\s*(?:///|//!)")
TAG = re.compile(r"@(?P<tag>file|target|param|return|see|deprecated|frozen|mapkey|spawnflag|usehl)\b(?P<rest>.*)")
SEPARATOR = re.compile(r"^[\s/*=_-]*$")


# ---------------------------------------------------------------------------
# Doc comment harvesting
# ---------------------------------------------------------------------------


@dataclass
class Doc:
    summary: str = ""
    body: list[str] = field(default_factory=list)
    tags: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))

    def empty(self) -> bool:
        return not self.summary and not self.body and not self.tags


def clean(line: str) -> str:
    """Strip comment markers and leading decoration from one comment line."""
    line = re.sub(r"^\s*(?:///<?|//!<?|//|/\*+|\*/|\*)", "", line)
    return line.strip()


def parse_doc(block: list[str]) -> Doc:
    """Turn a run of comment lines into a Doc, splitting @tags out of the prose."""
    doc = Doc()
    for raw in block:
        text = clean(raw)
        if not text or SEPARATOR.match(raw):
            if doc.body and doc.body[-1] != "":
                doc.body.append("")
            continue
        m = TAG.search(text)
        if m:
            doc.tags[m.group("tag")].append(m.group("rest").strip())
            continue
        if not doc.summary:
            doc.summary = text
        else:
            doc.body.append(text)
    while doc.body and doc.body[-1] == "":
        doc.body.pop()
    return doc


def harvest(path: Path) -> tuple[Doc, dict[int, Doc]]:
    """(file-level doc, {lineno: doc}) for one file.

    A definition's doc is the comment run immediately above it, plus any `//!<`
    trailing comment on the definition line itself. The file doc is a comment
    block at the very top that is not attached to any definition.
    """
    lines = path.read_text(encoding="latin-1").splitlines()
    by_line: dict[int, Doc] = {}

    # Walk backwards from each definition to collect the block above it.
    def block_above(idx: int) -> list[str]:
        out: list[str] = []
        i = idx - 1
        while i >= 0 and not lines[i].strip():
            i -= 1  # one blank line between doc and definition is fine
            if idx - i > 2:
                return []
        while i >= 0 and COMMENT_LINE.match(lines[i]):
            out.insert(0, lines[i])
            i -= 1
        # Half-Life style wraps real documentation in rules:
        #
        #     //=====================================
        #     // Animation hook. Resolves a framegroup name on the monster's
        #     // model via frameforname / frameduration ...
        #     //=====================================
        #
        # and it writes section banners the same way:
        #
        #     //-------------------------------------
        #     // Tunables / constants
        #     //-------------------------------------
        #
        # So the rules themselves cannot tell them apart. Strip the rules and
        # judge the prose: a banner is a short label, documentation is a
        # sentence. Discarding every rule-terminated block instead loses most of
        # the recovered documentation; keeping every one re-attributes each
        # banner to whichever definition happens to follow it.
        while out and SEPARATOR.match(out[0]):
            out.pop(0)
        while out and SEPARATOR.match(out[-1]):
            out.pop()
        prose = [ln for ln in out if clean(ln)]
        if not prose:
            return []
        if len(prose) == 1 and len(re.findall(r"[A-Za-z]{2,}", prose[0])) < 8:
            return []  # section banner
        return out

    for d in qc_common.scan_definitions([path]):
        if d.is_prototype:
            continue
        idx = d.lineno - 1
        block = block_above(idx)
        trailing = ""
        if idx < len(lines):
            spans, _ = qc_common.classify_line(lines[idx], False)
            trailing = "".join(
                lines[idx][s.start : s.end]
                for s in spans
                if s.kind == qc_common.SPAN_COMMENT
            ).strip()
        if trailing:
            block = block + [trailing]
        if block:
            doc = parse_doc(block)
            if not doc.empty():
                by_line[d.lineno] = doc

    # File header: leading comment run, unless it was consumed as a definition doc.
    head: list[str] = []
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    while i < len(lines) and COMMENT_LINE.match(lines[i]):
        head.append(lines[i])
        i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    consumed = any(d.lineno - 1 == i for d in qc_common.scan_definitions([path]))
    file_doc = Doc() if consumed or not head else parse_doc(head)
    return file_doc, by_line


