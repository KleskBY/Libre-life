def cmd_build(args) -> int:
    pages = build_pages()
    written = 0
    for rel, content in pages.items():
        dest = DOCS / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not dest.exists() or dest.read_text(encoding="utf-8") != content:
            dest.write_text(content, encoding="utf-8")
            written += 1
    print(f"{len(pages)} page(s), {written} written -> {DOCS}")
    return 0


def cmd_check(args) -> int:
    pages = build_pages()
    stale = [
        rel
        for rel, content in pages.items()
        if not (DOCS / rel).exists()
        or (DOCS / rel).read_text(encoding="utf-8") != content
    ]
    if stale:
        print(f"{len(stale)} page(s) out of date; run `python tools/qc_doc.py build`")
        for rel in stale[:20]:
            print(f"  {rel}")
        return 1
    print(f"docs/reference is up to date ({len(pages)} pages)")
    return 0


def cmd_coverage(args) -> int:
    tgts = qc_common.targets()
    files = {f for fs in tgts.values() for f in fs}
    rows = []
    for f in sorted(files):
        if qc_common.is_vendored(f) or not f.exists():
            continue
        _, by_line = harvest(f)
        defs = [
            d
            for d in qc_common.scan_definitions([f])
            if d.kind in ("function", "field") and not d.is_prototype
        ]
        if not defs:
            continue
        documented = sum(1 for d in defs if d.lineno in by_line)
        rows.append((documented / len(defs), documented, len(defs), qc_common.rel(f)))
    rows.sort()
    print(f"{'cov':>6}  {'doc':>5}/{'all':<5}  file")
    for pct, doc, total, rel in rows:
        if pct >= args.threshold:
            continue
        print(f"{pct * 100:5.0f}%  {doc:>5}/{total:<5}  {rel}")
    overall = sum(r[1] for r in rows) / max(1, sum(r[2] for r in rows))
    print(f"\noverall {overall * 100:.1f}% of public definitions documented")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build").set_defaults(fn=cmd_build)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    cov = sub.add_parser("coverage")
    cov.add_argument("--threshold", type=float, default=1.0)
    cov.set_defaults(fn=cmd_coverage)
    args = ap.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    raise SystemExit(main())
