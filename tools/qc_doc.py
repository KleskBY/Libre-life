def build_pages() -> dict[str, str]:
    """{relative path under docs/reference: file content}."""
    pages: dict[str, str] = {}
    locked = load_locked()
    tgts = qc_common.targets()

    # Which targets compile each file -- the thing Doxygen cannot express.
    file_targets: dict[Path, list[str]] = defaultdict(list)
    for tname, files in tgts.items():
        for f in files:
            file_targets[f].append(tname)

    all_defs: dict[Path, list[qc_common.Definition]] = {}
    docs_by_file: dict[Path, tuple[Doc, dict[int, Doc]]] = {}
    for f in sorted(file_targets):
        if qc_common.is_vendored(f) or not f.exists():
            continue
        all_defs[f] = qc_common.scan_definitions([f])
        docs_by_file[f] = harvest(f)

    for tname, files in tgts.items():
        for f in files:
            if f not in all_defs:
                continue
            rel = qc_common.rel(f)
            # `rel` already starts with the target directory for target-specific
            # files, but not for shared ones (gamedefs.qc, ui/*.qc), which need
            # the prefix to get one page per target they compile into.
            inner = rel[len(tname) + 1 :] if rel.startswith(tname + "/") else rel
            page_rel = f"{tname}/{inner.replace('.qc', '.md')}"
            pages[page_rel] = render_file_page(
                f, tname, file_targets[f], all_defs[f], docs_by_file[f], locked,
                up_to_root(page_rel),
            )
        pages[f"{tname}/index.md"] = render_target_index(tname, files, all_defs)

    pages["entities.md"] = render_entities(all_defs, docs_by_file, locked)
    pages["mapkeys.md"] = render_mapkeys(all_defs, docs_by_file, locked)
    pages["weapons.md"] = render_weapons()
    pages["cvars.md"] = render_cvars(tgts)
    pages["builtins.md"] = render_builtins(all_defs)
    pages["index.md"] = render_root_index(tgts, all_defs)
    return pages


def render_file_page(
    path: Path,
    tname: str,
    targets_of: list[str],
    defs: list[qc_common.Definition],
    docs: tuple[Doc, dict[int, Doc]],
    locked: dict[str, list[str]],
    prefix: str,
) -> str:
    file_doc, by_line = docs
    rel = qc_common.rel(path)
    out = [BANNER, f"# `{rel}`", ""]

    labels = ", ".join(TARGET_LABEL[t] for t in sorted(targets_of))
    out.append(f"**Compiles into:** {labels}")
    if len(targets_of) > 1:
        out.append("")
        out.append(
            "> Shared file — compiled once per target against a different engine "
            "ABI. Behaviour that must differ is guarded with "
            "`#ifdef SVQC` / `#ifdef CSQC` / `#ifdef MENUQC`."
        )
    out.append("")

    if not file_doc.empty():
        out += render_doc(file_doc) + [""]

    groups: dict[str, list[qc_common.Definition]] = defaultdict(list)
    for d in defs:
        if d.kind == "local" or d.is_prototype:
            continue
        groups[d.kind].append(d)

    titles = {
        "define": "Constants",
        "field": "Entity fields",
        "global": "Globals",
        "function": "Functions",
    }
    for kind in ("define", "field", "global", "function"):
        items = groups.get(kind)
        if not items:
            continue
        out += [f"## {titles[kind]}", ""]
        for d in sorted(items, key=lambda x: x.lineno):
            out.append(f"### `{d.name}`")
            out.append("")
            out.append(f"```c\n{signature(d)}\n```")
            out.append("")
            kind_key = {"function": "spawnfn", "field": "field"}.get(kind, "global")
            why = reasons_of(locked, d.name, kind_key) or locked.get(d.name, [])
            if why:
                out.append(f"> **FROZEN** — {', '.join(why)}. Renaming this "
                           f"builds clean and fails silently at runtime.")
                out.append("")
            doc = by_line.get(d.lineno)
            if doc and not doc.empty():
                out += render_doc(doc) + [""]
            out.append(src_link(path, d.lineno, prefix))
            out.append("")
    return "\n".join(out) + "\n"


def render_target_index(
    tname: str, files: list[Path], all_defs: dict[Path, list[qc_common.Definition]]
) -> str:
    out = [
        BANNER,
        f"# {TARGET_LABEL[tname]} reference",
        "",
        f"Compiled from `src/{tname}/{tname}.src` into `{TARGET_DAT[tname]}`.",
        "",
        "| File | Functions | Fields | Constants |",
        "| --- | ---: | ---: | ---: |",
    ]
    for f in files:
        defs = all_defs.get(f)
        if not defs:
            continue
        rel = qc_common.rel(f)
        n = lambda k: sum(1 for d in defs if d.kind == k and not d.is_prototype)  # noqa: E731
        inner = rel[len(tname) + 1 :] if rel.startswith(tname + "/") else rel
        link = inner.replace(".qc", ".md")
        out.append(f"| [`{rel}`]({link}) | {n('function')} | {n('field')} | {n('define')} |")
    return "\n".join(out) + "\n"


def render_entities(all_defs, docs_by_file, locked) -> str:
    """Every map-spawnable classname.

    The engine reads `"classname" "x"` from the BSP entity lump and calls the
    global QC function named exactly `x`. There is no spawnfunc table, so this
    list IS the contract.
    """
    out = [
        BANNER,
        "# Entity catalog",
        "",
        "Every classname a `.bsp` can spawn. The engine reads "
        '`"classname" "x"` from the entity lump and calls the global QC function '
        "named exactly `x` — there is no spawnfunc table in this project, so "
        "renaming one of these compiles clean and the entity simply never spawns.",
        "",
        "| Classname | Defined in | Summary |",
        "| --- | --- | --- |",
    ]
    rows = []
    for path, defs in all_defs.items():
        _, by_line = docs_by_file[path]
        for d in defs:
            if d.is_prototype or d.kind != "function":
                continue
            if not reasons_of(locked, d.name, "spawnfn"):
                continue
            doc = by_line.get(d.lineno)
            summary = (doc.summary if doc else "") or ""
            summary = summary.replace("|", "\\|")[:120]
            rel = qc_common.rel(path)
            rows.append((d.name, rel, d.lineno, summary))
    for name, rel, line, summary in sorted(rows):
        out.append(f"| `{name}` | [`{rel}:{line}`](../../src/{rel}#L{line}) | {summary} |")
    out += ["", f"**{len(rows)} spawnable classnames.**", ""]
    return "\n".join(out) + "\n"


def render_mapkeys(all_defs, docs_by_file, locked) -> str:
    """Fields bound by name to BSP keyvalues."""
    out = [
        BANNER,
        "# Map keyvalue reference",
        "",
        "`ED_ParseEdict` matches each BSP key against the progs field table by "
        "**exact, case-sensitive name**. A field listed here reads 0 or `\"\"` "
        "forever if renamed. Being assigned in QC does *not* unlock a key — that "
        "is why entities such as `env_beam` carry PascalCase fields like "
        "`BoltWidth`, which are Valve FGD spellings.",
        "",
        "Thirteen entities sidestep this by parsing `tokenize(__fullspawndata)` "
        "by hand. There the **key strings** are frozen but the field names are "
        "free — that is how `func_tank` maps HL's `yawrate` onto `tank_yawRate`.",
        "",
    ]

    def collect(paths, docs_lookup):
        rows, seen = [], set()
        for path in paths:
            if not path.exists():
                continue
            by_line = docs_lookup.get(path, (None, {}))[1]
            for d in qc_common.scan_definitions([path]):
                if d.kind != "field" or d.name in seen:
                    continue
                if not reasons_of(locked, d.name, "field"):
                    continue
                seen.add(d.name)
                doc = by_line.get(d.lineno)
                note = ((doc.summary if doc else "") or "").replace("|", "\\|")[:110]
                rows.append((d.name, d.ret or "float", qc_common.rel(path), d.lineno, note))
        return sorted(rows)

    def table(rows):
        lines = ["| Field | Type | Declared in | Notes |", "| --- | --- | --- | --- |"]
        for name, typ, rel, line, note in rows:
            lines.append(
                f"| `{name}` | `{typ}` | [`{rel}:{line}`](../../src/{rel}#L{line}) | {note} |"
            )
        return lines

    project = collect(sorted(all_defs), docs_by_file)

    # Stock-Quake system fields live in the vendored progsdefs.qc, which the
    # per-file API pages deliberately skip as engine ABI glue. They are still the
    # most-used map keys there are -- `target`, `targetname`, `spawnflags`,
    # `health`, `angles` -- so a mapper-facing page that omitted them would be
    # worse than useless.
    vendored_paths = sorted(
        {f for fs in qc_common.targets().values() for f in fs if qc_common.is_vendored(f)}
    )
    system = collect(vendored_paths, {})

    out += ["## Project fields", ""]
    out += table(project)
    out += [
        "",
        "## Stock Quake system fields",
        "",
        "Declared in the vendored `src/progsdefs.qc`, **above the "
        "`end_sys_fields` sentinel**. That region is order-locked as well as "
        "name-locked: it mirrors the engine's own struct layout, so fields "
        "cannot be renamed *or* reordered.",
        "",
    ]
    out += table(system)
    out += [
        "",
        f"**{len(project)} project fields + {len(system)} system fields "
        f"= {len(project) + len(system)} map-bound keys.**",
        "",
    ]
    return "\n".join(out) + "\n"


def render_weapons() -> str:
    """WID <-> WEAPON_* bit table, read straight out of the registry."""
    defs_txt = (SRC / "weapondefs.qc").read_text(encoding="latin-1")
    game_txt = (SRC / "gamedefs.qc").read_text(encoding="latin-1")

    wid = {
        m.group(1): int(m.group(2))
        for m in re.finditer(r"#define\s+(WID_\w+)\s+(\d+)", defs_txt)
    }
    bits: dict[str, str] = {}
    for m in re.finditer(r"#define\s+(WEAPON_\w+)\s+(\w+)", game_txt):
        bits[m.group(1)] = m.group(2)

    def bit_value(name: str, depth: int = 0) -> str:
        v = bits.get(name, "")
        if v.isdigit() or depth > 4:
            return v
        return bit_value(v, depth + 1) if v in bits else v

    names = dict(re.findall(r'weapon_name\[(WID_\w+)\]\s*=\s*"([^"]*)"', defs_txt))
    slots = dict(re.findall(r"weapon_slot\[(WID_\w+)\]\s*=\s*(\d+)", defs_txt))
    poss = dict(re.findall(r"weapon_pos\[(WID_\w+)\]\s*=\s*(\d+)", defs_txt))
    wbits = dict(re.findall(r"weapon_bit\s*\[(WID_\w+)\]\s*=\s*(WEAPON_\w+)", defs_txt))

    out = [
        BANNER,
        "# Weapon registry",
        "",
        "`src/weapondefs.qc` is the single source of truth, initialised once from "
        "`worldspawn` (SVQC) and once from `CSQC_Init` (CSQC).",
        "",
        "Two identifier spaces that are easy to confuse:",
        "",
        "- **`WID_*`** — small integer IDs, `1..WID_COUNT-1`. Doubles as the "
        "impulse number, so `impulse 3` is `WID_PYTHON`.",
        "- **`WEAPON_*`** — 32-bit **bitflags**, the on-the-wire format for "
        "`STAT_WEAPONS` and `self.weapon`.",
        "",
        "They are *not* interchangeable. Convert with `Weapon_BitFromID(id)` and "
        "`Weapon_IDFromBit(bit)`.",
        "",
        "| WID | # | Name | Slot | Pos | `WEAPON_*` bit | Value |",
        "| --- | ---: | --- | ---: | ---: | --- | ---: |",
    ]
    for name, num in sorted(wid.items(), key=lambda kv: kv[1]):
        if name == "WID_COUNT":
            continue
        bit = wbits.get(name, "")
        out.append(
            f"| `{name}` | {num} | {names.get(name, '')} | {slots.get(name, '')} "
            f"| {poss.get(name, '')} | `{bit}` | {bit_value(bit) if bit else ''} |"
        )
    out += [
        "",
        "Adding a weapon: bump `WID_COUNT`, add the `#define WID_FOO`, add an "
        "init block in `Weapon_RegistryInit()`, and reuse or add a `WEAPON_*` "
        "bit. The per-weapon select dispatch in "
        "`serverqc/weapons/weapons.qc` `Weapon_Update()` stays an explicit "
        "`if` chain — it is the one function-pointer hookup point.",
        "",
    ]
    return "\n".join(out) + "\n"


def render_cvars(tgts: dict[str, list[Path]]) -> str:
    pattern = re.compile(
        r"\b(?:cvar|cvar_string|cvar_set|registercvar|autocvar)\s*\(\s*\"([^\"]+)\""
    )
    found: dict[str, set[str]] = defaultdict(set)
    for tname, files in tgts.items():
        for f in files:
            if not f.exists() or qc_common.is_vendored(f):
                continue
            for name in pattern.findall(f.read_text(encoding="latin-1")):
                found[name].add(TARGET_LABEL[tname])
    out = [
        BANNER,
        "# Cvar reference",
        "",
        "Every cvar name the QC reads or writes, and which VMs touch it. Cvar "
        "names are a **data contract** (configs, autoexec, server operators) and "
        "are never renamed.",
        "",
        "| Cvar | Used by |",
        "| --- | --- |",
    ]
    for name in sorted(found):
        out.append(f"| `{name}` | {', '.join(sorted(found[name]))} |")
    out += ["", f"**{len(found)} cvars.**", ""]
    return "\n".join(out) + "\n"


def render_builtins(all_defs) -> str:
    pattern = re.compile(
        r"^\s*(?P<sig>[\w()\s,.*\[\]]+?)\s*(?P<name>\w+)\s*=\s*#(?P<num>\d+)\s*;"
    )
    rows: list[tuple[int, str, str, str]] = []
    seen: set[str] = set()
    for f in sorted(SRC.rglob("*.qc")):
        rel = qc_common.rel(f)
        for i, line in enumerate(f.read_text(encoding="latin-1").splitlines(), 1):
            m = pattern.match(line)
            if not m or m.group("name") in seen:
                continue
            seen.add(m.group("name"))
            rows.append((int(m.group("num")), m.group("name"), m.group("sig").strip(), rel))
    out = [
        BANNER,
        "# Builtin bindings",
        "",
        "Engine functions bound by number. **The name string is the binding** for "
        "`= #0:name` forms, so these are frozen. Before adding one, check the "
        "FTE and DarkPlaces extension headers — the builtin probably already exists.",
        "",
        "| # | Name | Signature | Declared in |",
        "| ---: | --- | --- | --- |",
    ]
    for num, name, sig, rel in sorted(rows):
        out.append(f"| {num} | `{name}` | `{sig}` | `{rel}` |")
    out += ["", f"**{len(rows)} builtins bound.**", ""]
    return "\n".join(out) + "\n"


